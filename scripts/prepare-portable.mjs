import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const dist = new URL("../build/web/", import.meta.url);
const target = new URL("../build/launcher/", import.meta.url);
const source = new URL("../portable/", import.meta.url);
await readFile(new URL("index.html", dist));
// Only this fixed, generated directory is replaced. User libraries are in IndexedDB.
await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
for (const name of ["main.go", "main_test.go", "go.mod", "GO-LICENSE"]) {
  await cp(new URL(name, source), new URL(name, target));
}
await cp(dist, new URL("public/", target), { recursive: true });
await writeFile(
  new URL("assets.go", target),
  `// Generated by scripts/prepare-portable.mjs; do not edit.\npackage main\n\nimport "embed"\n\n//go:embed all:public\nvar embeddedAssets embed.FS\n\nfunc init() { assets = embeddedAssets }\n`,
);
console.log(`Prepared embedded application: ${fileURLToPath(target)}`);
